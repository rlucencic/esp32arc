#define CYLINDER_BYTES  (16u * 63 * 512)

uint32_t arc_hd_blank_size(int i)
{
    return i >= 0 && i < (int)(sizeof(s_templates) / sizeof(s_templates[0]))
               ? s_templates[i].cylinders * CYLINDER_BYTES : 0;
}

/* The template for an image of `bytes`, NULL if there's none */
static const template_t *find(uint32_t bytes)
{
    for (size_t i = 0; i < sizeof(s_templates) / sizeof(s_templates[0]); i++) {
        if (s_templates[i].cylinders * CYLINDER_BYTES == bytes) {
            return &s_templates[i];
        }
    }
    return NULL;
}

bool arc_hd_create(const char *path, uint32_t bytes)
{
    FILE *f = fopen(path, "wb");
    if (!f) {
        return false;
    }
    const template_t *t = find(bytes);
    static uint8_t block[4096];
    size_t next = 0;                    /* the template's next run */
    bool ok = true;
    for (uint32_t done = 0; ok && done < bytes; done += sizeof(block)) {
        uint32_t n = bytes - done < sizeof(block) ? bytes - done : (uint32_t)sizeof(block);
        memset(block, 0, sizeof(block));
        while (t && next < t->run_count && t->runs[next].at < done + n) {
            const run_t *r = &t->runs[next];
            for (uint32_t k = 0; k < r->len; k++) {
                uint32_t at = r->at + k;
                if (at >= done && at < done + n) {
                    block[at - done] = t->data[r->data + k];
                }
            }
            if (r->at + r->len > done + n) {
                break;                  /* it goes on into the next block */
            }
            next++;
        }
        ok = fwrite(block, 1, n, f) == n;
    }
    return fclose(f) == 0 && ok;
}
